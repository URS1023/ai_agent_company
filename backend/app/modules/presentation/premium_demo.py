def _with_topic_descriptions(profile: dict) -> dict:
    """为缺少"抓手"条目的画像补一组通用描述（围绕该画像主题）。

    只在 ``levers`` 为空时补充，已有业务描述的画像原样返回，避免覆盖更可信的内容。
    """

    profile = deepcopy(profile)
    topic = profile["title"]
    if profile.get("levers"):
        return profile
    profile["levers"] = [
        ("目标对齐", f"围绕《{topic}》建立结果指标与责任边界"),
        ("流程重构", "先改变关键行为，再决定系统和工具投入"),
        ("数据闭环", "统一事实口径并持续跟踪领先指标"),
        ("组织保障", "明确负责人、复盘节奏和退出标准"),
    ]
    return profile


