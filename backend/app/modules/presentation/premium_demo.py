def preview_slide_numbers(template_id: str) -> tuple[int, int, int, int]:
    """返回该模板拼版预览要渲染的 4 个页码（按画像变体错开，让不同模板的预览不雷同）。"""

    profile = PROFILES[template_id]
    sequence = BASE_SEQUENCES[int(profile.get("sequence", 0)) % len(BASE_SEQUENCES)]
    selected = [1]
    for role in profile.get("preview") or ():
        selected.append(sequence.index(role) + 2)
    while len(selected) < 4:
        candidate = 2 + len(selected) * 2
        if candidate not in selected:
            selected.append(candidate)
    return tuple(selected[:4])
