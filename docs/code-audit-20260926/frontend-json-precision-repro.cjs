/* 中文说明：离线复现开始节点 JSON 字段先行舍入导致提交校验失效，全部使用内存数据。 */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const ts = require(path.join(root, 'apps/analytics/node_modules/typescript'));
const vue = require(path.join(root, 'apps/analytics/node_modules/vue'));
const { parseWorkflowJson } = require(path.join(root, 'apps/analytics/src/utils/workflowJson.js'));
const text = fs.readFileSync(path.join(root, 'apps/analytics/src/components/workflows/WorkflowStartInputForm.vue'), 'utf8');
const script = text.match(/<script setup lang="ts">([\s\S]*?)<\/script>/)[1].replace(/^import .*$/gm, '');
const field = { variable: 'payload', type: 'json_object', label: '参数', required: true };
let emitted;
const context = { ...vue, watch() {}, defineProps: () => ({ modelValue: '{}', variables: [field], disabled: false }), defineEmits: () => (name, value) => { if (name === 'update:modelValue') emitted = value; } };
const code = ts.transpileModule(script + '\nglobalThis.editJson = editJson;', { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
vm.runInNewContext(code, context);
const original = '{"amount":0.10000000000000000001}';
assert.throws(() => parseWorkflowJson(original), RangeError);
context.editJson(field, { target: { value: original } });
assert.equal(parseWorkflowJson(emitted).payload.amount, 0.1);
console.log('CONFIRMED 原始 JSON 被 parseWorkflowJson 拒绝，但开始节点表单先舍入成 ' + emitted.replaceAll('\n', '') + ' 后可通过相同提交校验。');
